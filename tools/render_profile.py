def expected_assets() -> dict[str, str]:
    result = {}
    for theme in THEMES:
        for mobile in (False, True):
            for kind in TITLES:
                name = f'{kind}-{theme}' + ('-mobile' if mobile else '') + '.svg'
                result[name] = render(kind, theme, mobile)
    for theme in THEMES:
        result[f'gds-{theme}-motion.svg'] = render('gds', theme, motion=True)
    result['social-preview.svg'] = social()
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check exact output without writing.')
    parser.add_argument('--output', type=Path, default=ROOT/'assets/profile')
    args = parser.parse_args()
    assets = expected_assets()
    if args.check:
        errors = [name for name, data in assets.items()
                  if not (args.output/name).is_file() or (args.output/name).read_bytes() != data.encode('utf-8')]
        errors += sorted(p.name for p in args.output.glob('*.svg') if p.name not in assets)
        if errors:
            print('SVG drift: ' + ', '.join(errors))
            return 1
        print(f'PASS: {len(assets)} SVG assets reproduce byte-for-byte.')
    else:
        args.output.mkdir(parents=True, exist_ok=True)
        for name, data in assets.items():
            (args.output/name).write_bytes(data.encode('utf-8'))
        print(f'Wrote {len(assets)} SVG assets to {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
