class Drawing:
    """Small, explicit SVG vocabulary; all coordinates remain reviewable."""
    def __init__(self, width: int, height: int, theme: str, title: str, desc: str):
        self.w, self.h, self.c = width, height, THEMES[theme]
        c = self.c
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
            f'<title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>',
            '<!-- Generated by tools/render_profile.py. Edit the drawing source, not this file. -->',
            f'<defs><pattern id="grid" width="24" height="24" patternUnits="userSpaceOnUse"><path d="M24 0H0V24" fill="none" stroke="{c["grid"]}"/></pattern>',
            f'<marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto" markerUnits="userSpaceOnUse"><path d="m2 1 5 3-5 3" fill="none" stroke="{c["accent"]}" stroke-width="1.5"/></marker></defs>',
            f'<rect x="1" y="1" width="{width-2}" height="{height-2}" rx="10" fill="{c["bg"]}" stroke="{c["line"]}"/>',
            f'<rect x="16" y="16" width="{width-32}" height="{height-32}" fill="url(#grid)" opacity=".7"/>',
        ]
        for x, y in ((16, 16), (width-16, 16), (16, height-16), (width-16, height-16)):
            self.path(f'M{x-4} {y}h8M{x} {y-4}v8', 'line', 1)

    def text(self, x: float, y: float, text: str, size: int = 22,
             color: str = 'ink', weight: int = 400, anchor: str = 'start', mono: bool = False):
        font = 'monospace' if mono else 'Arial, Helvetica, sans-serif'
        self.parts.append(f'<text x="{x}" y="{y}" font-family="{font}" font-size="{size}" font-weight="{weight}" text-anchor="{anchor}" fill="{self.c[color]}">{escape(text)}</text>')

    def rect(self, x: float, y: float, w: float, h: float, fill: str = 'panel', stroke: str = 'line', radius: int = 5):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{self.c[fill]}" stroke="{self.c[stroke]}"/>')

    def path(self, d: str, color: str = 'accent', width: float = 1.6,
             arrow: bool = False, dashed: bool = False):
        extra = (' marker-end="url(#arrow)"' if arrow else '') + (' stroke-dasharray="5 5"' if dashed else '')
        self.parts.append(f'<path d="{d}" fill="none" stroke="{self.c[color]}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"{extra}/>')

    def node(self, x: int, y: int, w: int, title: str, sub: str = '', active: bool = False, small: bool = False):
        h = 66 if sub else 48
        self.rect(x, y, w, h, 'wash' if active else 'panel', 'accent' if active else 'line')
        self.path(f'M{x} {y+12}V{y}h12', width=2)
        self.text(x+w/2, y+(28 if sub else 32), title, 22 if small else 23, weight=600, anchor='middle')
        if sub:
            self.text(x+w/2, y+51, sub, 18, 'muted', anchor='middle')

    def stack(self, cx: int, cy: int, scale: float = 1):
        """Exploded repository sheets, not an invented product logo."""
        self.parts.append(f'<g transform="translate({cx} {cy}) scale({scale})">')
        for offset in (32, 16, 0):
            self.parts.append(f'<path d="M-68 {offset} 0 {offset-34} 68 {offset} 0 {offset+34}Z" fill="{self.c["panel"]}" stroke="{self.c["line"]}" stroke-width="1.5"/>')
        self.path('M-68 0 0 34 68 0', width=2)
        self.path('M-36 -4-10 9M-22 -11 15 8M-8 -18 34 3', 'muted', 1.5)
        self.path('M0 34v32', dashed=True)
        self.parts.append('</g>')

    def finish(self) -> str:
        return '\n'.join(self.parts + ['</svg>', ''])


